export function translate(
  key: string,
  lang: Language = 'en',
  vars?: Record<string, string | number>
): string {
  const text = DICTIONARY[lang]?.[key] || DICTIONARY.en[key] || key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
